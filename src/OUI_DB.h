// Búsqueda lineal (rápida con ~100 elementos)
inline const char* buscarOUI(uint8_t* mac) {
    uint32_t oui = (mac[0] << 16) | (mac[1] << 8) | mac[2];
    for (int i = 0; i < sizeof(ouiDB)/sizeof(ouiDB[0]); i++) {
        OUIRecord reg;
        memcpy_P(&reg, &ouiDB[i], sizeof(OUIRecord));
        if (reg.oui == oui) {
            return reg.nombre;
        }
    }
    return "Desconocido";
}
